  String translate(String key, {Map<String, String>? args}) {
    final langCode = locale.languageCode;
    String? value = _localizedValues[langCode]?[key];
    // Fallback to English if translation is missing
    value ??= _localizedValues['en']?[key];
    // Fallback to key itself
    if (value == null) return key;

    if (args != null && args.isNotEmpty) {
      args.forEach((placeholder, replacement) {
        value = value!.replaceAll('{$placeholder}', replacement);
      });
    }

    return value!;
  }

  static String trOf(String langCode, String key, {Map<String, String>? args}) {
    String? value = _localizedValues[langCode]?[key];
    value ??= _localizedValues['en']?[key];
    if (value == null) return key;

    if (args != null && args.isNotEmpty) {
      args.forEach((placeholder, replacement) {
        value = value!.replaceAll('{$placeholder}', replacement);
      });
    }
    return value!;
  }
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  // languageCode is the user-chosen language from localeProvider.
  // Flutter's locale is always 'en' so GlobalMaterialLocalizations never fails,
  // but we pass our own language code here to serve correct translations.
  final String languageCode;

  const AppLocalizationsDelegate([this.languageCode = 'en']);

  @override
  bool isSupported(Locale locale) => true; // always accept; we use languageCode

  @override
  Future<AppLocalizations> load(Locale locale) {
    return SynchronousFuture<AppLocalizations>(
      AppLocalizations(Locale(languageCode)),
    );
  }

  @override
  bool shouldReload(AppLocalizationsDelegate old) => old.languageCode != languageCode;
}

extension AppLocalizationExtension on BuildContext {
  String tr(String key, {Map<String, String>? args}) {
    final loc = AppLocalizations.of(this);
    if (loc == null) return key;
    return loc.translate(key, args: args);
  }
}
