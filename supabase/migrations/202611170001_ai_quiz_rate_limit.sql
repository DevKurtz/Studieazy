-- Server-side AI abuse and cost controls. Request content is never stored.
create table if not exists public.ai_quiz_request_usage (
  id bigint generated by default as identity primary key,
  user_key text not null check (length(user_key) = 64),
  requested_at timestamptz not null default clock_timestamp(),
  status text not null default 'in_progress'
    check (status in ('in_progress', 'completed')),
  lease_until timestamptz not null
);

create index if not exists ai_quiz_request_usage_user_time_idx
  on public.ai_quiz_request_usage (user_key, requested_at desc);

create index if not exists ai_quiz_request_usage_time_idx
  on public.ai_quiz_request_usage (requested_at desc);

create index if not exists ai_quiz_request_usage_active_idx
  on public.ai_quiz_request_usage (lease_until)
  where status = 'in_progress';

alter table public.ai_quiz_request_usage enable row level security;
revoke all on table public.ai_quiz_request_usage from public, anon, authenticated;
grant all on table public.ai_quiz_request_usage to service_role;
revoke all on sequence public.ai_quiz_request_usage_id_seq from public, anon, authenticated;
grant usage, select on sequence public.ai_quiz_request_usage_id_seq to service_role;

create or replace function public.consume_ai_quiz_quota(p_user_key text)
returns table (
  allowed boolean,
  limit_kind text,
  retry_after_seconds integer,
  request_id bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := pg_catalog.clock_timestamp();
  v_user_minute_count integer;
  v_user_day_count integer;
  v_global_day_count integer;
  v_active_count integer;
  v_retry integer;
  v_request_id bigint;
begin
  if p_user_key is null or length(p_user_key) <> 64 then
    raise exception 'A hashed user key is required';
  end if;

  -- Serialize the short admission check so simultaneous requests cannot race
  -- past the shared project cap or a per-user cap.
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('ai-quiz-global', 0)
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('ai-quiz-user:' || p_user_key, 0)
  );

  delete from public.ai_quiz_request_usage
  where requested_at < v_now - interval '7 days';

  select count(*)::integer,
    greatest(1, ceil(extract(epoch from (
      min(requested_at) + interval '1 minute' - v_now
    )))::integer)
  into v_user_minute_count, v_retry
  from public.ai_quiz_request_usage
  where user_key = p_user_key
    and requested_at > v_now - interval '1 minute';

  if v_user_minute_count >= 2 then
    return query select false, 'per_minute'::text, v_retry, null::bigint;
    return;
  end if;

  select count(*)::integer,
    greatest(1, ceil(extract(epoch from (
      min(requested_at) + interval '24 hours' - v_now
    )))::integer)
  into v_user_day_count, v_retry
  from public.ai_quiz_request_usage
  where user_key = p_user_key
    and requested_at > v_now - interval '24 hours';

  if v_user_day_count >= 10 then
    return query select false, 'per_day'::text, v_retry, null::bigint;
    return;
  end if;

  select count(*)::integer,
    greatest(1, ceil(extract(epoch from (
      min(requested_at) + interval '24 hours' - v_now
    )))::integer)
  into v_global_day_count, v_retry
  from public.ai_quiz_request_usage
  where requested_at > v_now - interval '24 hours';

  if v_global_day_count >= 150 then
    return query select false, 'project_daily_cap'::text, v_retry, null::bigint;
    return;
  end if;

  select count(*)::integer,
    greatest(1, ceil(extract(epoch from (
      min(lease_until) - v_now
    )))::integer)
  into v_active_count, v_retry
  from public.ai_quiz_request_usage
  where status = 'in_progress'
    and lease_until > v_now;

  if v_active_count >= 10 then
    return query select false, 'concurrency'::text, v_retry, null::bigint;
    return;
  end if;

  insert into public.ai_quiz_request_usage (user_key, requested_at, status, lease_until)
  values (p_user_key, v_now, 'in_progress', v_now + interval '130 seconds')
  returning id into v_request_id;

  return query select true, 'allowed'::text, 0, v_request_id;
end;
$$;

revoke all on function public.consume_ai_quiz_quota(text) from public, anon, authenticated;
grant execute on function public.consume_ai_quiz_quota(text) to service_role;

create or replace function public.finish_ai_quiz_request(p_request_id bigint)
returns void
language sql
security definer
set search_path = ''
as $$
  update public.ai_quiz_request_usage
  set status = 'completed', lease_until = pg_catalog.clock_timestamp()
  where id = p_request_id and status = 'in_progress';
$$;

revoke all on function public.finish_ai_quiz_request(bigint) from public, anon, authenticated;
grant execute on function public.finish_ai_quiz_request(bigint) to service_role;
